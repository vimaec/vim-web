/** Attributes worth keeping off a Fluent path. `fill` is dropped: the root carries the caller's. */
const KEEP = ['d', 'fill-rule', 'clip-rule']

function readIcon (base) {
  const file = join(ICONS, `${base}_20_regular.svg`)
  const svg = readFileSync(file, 'utf8')
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1]
  if (!viewBox) throw new Error(`no viewBox in ${file}`)

  const children = []
  for (const tag of svg.matchAll(/<path\b([^>]*)\/?>/g)) {
    const attrs = {}
    for (const attr of tag[1].matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
      if (KEEP.includes(attr[1])) attrs[attr[1]] = attr[2]
    }
    if (attrs.d) children.push({ tag: 'path', attrs })
  }
  if (!children.length) throw new Error(`no paths in ${file}`)
  return { viewBox, fill: '$fill', children }
}

