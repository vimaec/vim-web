// One-shot generator for src/vim-web/icons/iconData.ts.
//
//   node scripts/generate-icons.mjs
//
// Redraws the icon set from Fluent UI System Icons (MIT), Microsoft's successor to the Segoe MDL2
// glyph font VIM Flex uses. We cannot use MDL2 itself: it is an OS font, so the codepoints would be
// tofu on any non-Windows browser, and its licence covers neither non-Microsoft platforms nor
// redistribution to third parties (see styles/fonts/Segoe_EULA.txt in the design system). Fluent
// shares MDL2's design language and ships as plain SVG, so the viewer reads like Flex without the
// font.
//
// Every icon comes from the 20px regular weight, which gives one optical weight across the set
// (the hand-drawn originals mixed 256, 50 and 20 unit grids). Names are ours and stay put — they
// are public API; only the artwork changes. A name whose meaning Fluent has no word for takes the
// nearest primitive of the same family, which is what Flex does with MDL2.
